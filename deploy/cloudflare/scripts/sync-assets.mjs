#!/usr/bin/env node
// Copies the shared browser and agent assets of the Backyard repository into
// src/generated/ as importable TypeScript string modules, so the Worker serves
// byte-identical SDK files, hub UI and agent docs as the Go server (SPEC §2.1):
//
//   web/sdk/backyard.{js,mjs,d.ts}  → src/generated/sdk.ts
//   web/hub/**                      → src/generated/hub.ts
//   skills/backyard/**              → src/generated/skills.ts
//   internal/mcpremote/tools.json   → src/generated/mcp.ts (the Claude connector's
//                                     tool catalog, SPEC §14.1: MCP_CATALOG)
//
// It also copies the shared query-semantics cases of SPEC §5.2 for the test
// suite (not bundled into the Worker):
//
//   internal/docstore/conformance/querycases.json → test/generated/querycases.json
//
// and writes the version the Worker reports (/__backyard/api/deploy/info):
//
//   BACKYARD_VERSION (e.g. 1.2.3 or 1.2.3-rc.1; scripts/pack.mjs sets it for a
//   release), else "<package.json version>-dev" → src/generated/version.ts
//
// An invalid BACKYARD_VERSION (not a semantic version) exits 1 before anything
// is written. version.ts is not part of ASSETS_HASH.
//
// Missing sources (e.g. while they are being written) become placeholders with
// a warning, so `npm test` and `wrangler dev` keep working. The repository root
// defaults to ../.. and can be overridden with BACKYARD_REPO_ROOT.
//
// Usage: [BACKYARD_VERSION=<semver>] node scripts/sync-assets.mjs [--check] [--strict]
//   --check   exit 1 if a generated file is out of date (no writes)
//   --strict  exit 1 instead of using placeholders (npm run build, setup,
//             scripts/pack.mjs), so a partial checkout never ships a Worker
//             without its SDK, hub or docs. Implied when wrangler runs this
//             script as the build step of anything but `wrangler dev` /
//             `wrangler types` (WRANGLER_COMMAND), e.g. a plain `npx wrangler deploy`.

import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const pkgDir = resolve(here, "..");
const repoRoot = resolve(process.env.BACKYARD_REPO_ROOT || join(pkgDir, "..", ".."));
const outDir = join(pkgDir, "src", "generated");
const testOutDir = join(pkgDir, "test", "generated");
const check = process.argv.includes("--check");
// wrangler sets WRANGLER_COMMAND for its custom build step ("dev", "deploy",
// "versions upload", "types", …): anything that uploads must be complete.
const wranglerCommand = (process.env.WRANGLER_COMMAND ?? "").trim();
const strict = process.argv.includes("--strict") || (wranglerCommand !== "" && !/^(dev|types)\b/.test(wranglerCommand));

// --- Version ---------------------------------------------------------------

/** A release version: 1.2.3, or 1.2.3-<pre-release> (the same rule as scripts/pack.mjs). */
const VERSION_RE = /^\d+\.\d+\.\d+(-[0-9A-Za-z.-]+)?$/;
const requestedVersion = String(process.env.BACKYARD_VERSION ?? "").trim();
if (requestedVersion !== "" && !VERSION_RE.test(requestedVersion)) {
  console.error(
    `sync-assets: BACKYARD_VERSION must be a semantic version such as 1.2.3 or 1.2.3-rc.1 (got ${JSON.stringify(requestedVersion)}); nothing was written`,
  );
  process.exit(1);
}
/** The version the Worker reports: BACKYARD_VERSION, else "<package.json version>-dev". */
function buildVersion() {
  if (requestedVersion) return requestedVersion;
  let pkgVersion = "0.0.0";
  try {
    const v = JSON.parse(readFileSync(join(pkgDir, "package.json"), "utf8")).version;
    if (typeof v === "string" && VERSION_RE.test(v)) pkgVersion = v;
  } catch {
    /* no package.json (a partial copy): 0.0.0-dev */
  }
  return `${pkgVersion}-dev`;
}

const TEXT_EXT = new Set([".html", ".css", ".js", ".mjs", ".ts", ".json", ".svg", ".txt", ".md", ".map", ".xml", ".webmanifest"]);
const warnings = [];

function readText(path, placeholder, normalize = false) {
  try {
    const s = readFileSync(path, "utf8");
    return normalize ? s.replace(/\r\n/g, "\n") : s;
  } catch {
    warnings.push(`missing ${relative(repoRoot, path)}: using a placeholder`);
    return placeholder;
  }
}

/** Lists files under dir recursively (sorted, "/"-separated relative paths). */
function walk(dir) {
  const out = [];
  if (!existsSync(dir)) return out;
  const visit = (d) => {
    for (const name of readdirSync(d).sort()) {
      if (name.startsWith(".") || name.startsWith("_")) continue;
      const p = join(d, name);
      const st = statSync(p);
      if (st.isDirectory()) visit(p);
      else if (st.isFile()) out.push(relative(dir, p).split(sep).join("/"));
    }
  };
  visit(dir);
  return out;
}

const banner =
  "// GENERATED by scripts/sync-assets.mjs — do not edit. Regenerate with `npm run sync`.\n" +
  "/* eslint-disable */\n";

function lit(s) {
  return JSON.stringify(s);
}

// --- SDK -------------------------------------------------------------------

const sdkDir = join(repoRoot, "web", "sdk");
const sdkPlaceholder = (name) =>
  `/* Backyard SDK placeholder: ${name} was missing when the Worker was built (run npm run sync). */\n` +
  (name.endsWith(".d.ts") ? "export {};\n" : 'console.warn("Backyard SDK not bundled in this build");\n');
const sdkJS = readText(join(sdkDir, "backyard.js"), sdkPlaceholder("backyard.js"));
const sdkMJS = readText(join(sdkDir, "backyard.mjs"), sdkPlaceholder("backyard.mjs"));
const sdkDTS = readText(join(sdkDir, "backyard.d.ts"), sdkPlaceholder("backyard.d.ts"));
const sdkTS =
  banner +
  `/** Classic-script SDK (web/sdk/backyard.js). */\nexport const SDK_JS: string = ${lit(sdkJS)};\n` +
  `/** ES module SDK (web/sdk/backyard.mjs). */\nexport const SDK_MJS: string = ${lit(sdkMJS)};\n` +
  `/** TypeScript declarations (web/sdk/backyard.d.ts). */\nexport const SDK_DTS: string = ${lit(sdkDTS)};\n`;

// --- Hub UI ----------------------------------------------------------------

const hubDir = join(repoRoot, "web", "hub");
const hubFiles = walk(hubDir);
if (hubFiles.length === 0) warnings.push("missing web/hub: using a placeholder hub page");
const hubEntries = [];
for (const rel of hubFiles) {
  const p = join(hubDir, rel);
  const ext = rel.slice(rel.lastIndexOf(".")).toLowerCase();
  if (TEXT_EXT.has(ext)) {
    hubEntries.push(`  ${lit(rel)}: { text: ${lit(readFileSync(p, "utf8"))} },`);
  } else {
    hubEntries.push(`  ${lit(rel)}: { base64: ${lit(readFileSync(p).toString("base64"))} },`);
  }
}
if (!hubFiles.includes("index.html")) {
  hubEntries.push(
    `  "index.html": { text: ${lit(
      '<!doctype html><meta charset="utf-8"><title>Backyard</title><h1>Backyard</h1><p>The hub UI was not bundled in this build (run <code>npm run sync</code>).</p>\n',
    )} },`,
  );
}
if (!hubFiles.includes("docs.html")) {
  hubEntries.push(
    `  "docs.html": { text: ${lit(
      '<!doctype html><meta charset="utf-8"><title>Backyard docs</title><h1>Backyard docs</h1><p>See <a href="/llms-full.txt">/llms-full.txt</a>.</p>\n',
    )} },`,
  );
}
const hubTS =
  banner +
  "/** A hub UI file: UTF-8 text, or base64 for binary assets. */\n" +
  "export interface HubFile {\n  text?: string;\n  base64?: string;\n}\n\n" +
  "/** web/hub/** keyed by relative path (served at / on the hub). */\n" +
  `export const HUB_FILES: Record<string, HubFile> = {\n${hubEntries.join("\n")}\n};\n`;

// --- Skill / agent docs ----------------------------------------------------

const skillDir = join(repoRoot, "skills", "backyard");
const skillMD = readText(
  join(skillDir, "SKILL.md"),
  "---\nname: backyard\ndescription: Backyard docs placeholder\n---\n\n# Backyard\n\nThe agent docs were not bundled in this build.\n",
  true,
);
const refDir = join(skillDir, "references");
const refs = walk(refDir).filter((f) => /^[a-z0-9][a-z0-9_-]{0,63}\.md$/.test(f));
if (refs.length === 0) warnings.push("missing skills/backyard/references: no reference docs bundled");
const refEntries = refs.map((f) => `  ${lit(f.slice(0, -3))}: ${lit(readText(join(refDir, f), "", true))},`);
const skillsTS =
  banner +
  `/** skills/backyard/SKILL.md (with YAML front matter). */\nexport const SKILL_MD: string = ${lit(skillMD)};\n\n` +
  `/** skills/backyard/references/<name>.md keyed by name. */\nexport const REFERENCES: Record<string, string> = {\n${refEntries.join("\n")}\n};\n`;

// --- Claude connector tool catalog -------------------------------------------

// The normative catalog of the remote MCP endpoint (SPEC §14.1), which the Go
// server embeds: tools/list returns its tools verbatim, initialize its
// instructions. A missing or unparsable file becomes an empty catalog with a
// warning (a build with --strict refuses it).
const toolsRel = "internal/mcpremote/tools.json";
const toolsPlaceholder = {
  instructions: "The Claude connector's tool catalog was not bundled in this build (run npm run sync).",
  tools: [],
};
let mcpCatalog = toolsPlaceholder;
try {
  const parsed = JSON.parse(readFileSync(join(repoRoot, toolsRel), "utf8"));
  const tools = parsed?.tools;
  if (typeof parsed?.instructions !== "string" || !Array.isArray(tools) || tools.some((t) => typeof t?.name !== "string" || typeof t?.inputSchema !== "object")) {
    throw new Error("expected {instructions, tools: [{name, inputSchema, …}]}");
  }
  mcpCatalog = parsed;
} catch (e) {
  warnings.push(e.code === "ENOENT" ? `missing ${toolsRel}: using a placeholder` : `invalid ${toolsRel} (${e.message}): using a placeholder`);
}
const mcpTS =
  banner +
  "/** A tool of the catalog (MCP Tool: name, title, description, inputSchema, annotations). */\n" +
  "export interface McpTool {\n  name: string;\n  title?: string;\n  description?: string;\n  inputSchema: Record<string, unknown>;\n  annotations?: Record<string, unknown>;\n}\n\n" +
  `/** ${toolsRel}: the connector's instructions and tools (SPEC §14.1). */\n` +
  `export const MCP_CATALOG: { instructions: string; tools: McpTool[] } = ${JSON.stringify(mcpCatalog, null, 2)};\n`;

// --- Test fixtures (not part of the Worker) ---------------------------------

// The shared, language-neutral query cases (SPEC §5.2) that every Backyard
// document store runs; test/querycases.test.ts runs them against SiteDO. A
// missing file becomes a marked placeholder, which that test reports as a
// failure (it never passes vacuously). Never needed for a deploy.
const queryCasesRel = "internal/docstore/conformance/querycases.json";
const testWarnings = [];
let queryCasesJSON;
try {
  const raw = readFileSync(join(repoRoot, queryCasesRel), "utf8");
  JSON.parse(raw); // a broken file becomes the marked placeholder too
  queryCasesJSON = raw.replace(/\r\n/g, "\n");
} catch (e) {
  testWarnings.push(`cannot read ${queryCasesRel} (${e.code ?? e.message}): the shared query cases will fail`);
  queryCasesJSON = JSON.stringify({ version: 0, missing: queryCasesRel, collections: {}, cases: [] }, null, 2) + "\n";
}

// --- Write -----------------------------------------------------------------

const outputs = { "sdk.ts": sdkTS, "hub.ts": hubTS, "skills.ts": skillsTS, "mcp.ts": mcpTS };
const digest = createHash("sha256");
for (const k of Object.keys(outputs).sort()) digest.update(k).update(outputs[k]);
outputs["index.ts"] =
  banner +
  `/** Content hash of the bundled assets (changes whenever a source file changes). */\nexport const ASSETS_HASH = ${lit(
    digest.digest("hex").slice(0, 16),
  )};\n`;
// Outside the ASSETS_HASH digest: the same assets keep their hash across versions.
const versionTS =
  "// GENERATED by scripts/sync-assets.mjs — do not edit.\n" +
  '/** Version reported by /__backyard/api/deploy/info: BACKYARD_VERSION at build time, else "<package.json version>-dev". */\n' +
  `export const BUILD_VERSION = ${lit(buildVersion())};\n`;

if (strict && warnings.length) {
  const missing = warnings.map((w) => w.replace(/: (?:using a placeholder|no reference docs bundled).*$/, ""));
  console.error(
    [
      `sync-assets: cannot build the Worker: it bundles the browser SDK (web/sdk), the hub UI (web/hub), the`,
      `agent docs (skills/backyard) and the Claude connector's tool catalog (internal/mcpremote/tools.json)`,
      `of the Backyard repository, and these are missing under ${repoRoot}:`,
      ...missing.map((m) => `  - ${m.replace(/^missing /, "")}`),
      `Build from a complete checkout (git clone https://github.com/thasami/backyard.git, then`,
      `cd backyard/deploy/cloudflare), or point BACKYARD_REPO_ROOT at one. Placeholders are only`,
      `used for local development and tests (npm run sync without --strict).`,
      `No checkout needed to deploy: backyard cloudflare setup (a release build of the CLI) or, once a`,
      `Backyard release has published it to npm, npx backyard-cloudflare setup uses the prebuilt Worker`,
      `of the package.`,
    ].join("\n"),
  );
  process.exit(1);
}

let stale = false;
/** Writes (or, with --check, compares) one generated file. */
function emit(dir, name, content) {
  const p = join(dir, name);
  let current = null;
  try {
    current = readFileSync(p, "utf8");
  } catch {
    /* missing */
  }
  if (current === content) return;
  stale = true;
  if (!check) {
    mkdirSync(dir, { recursive: true });
    writeFileSync(p, content);
  }
}
for (const [name, content] of Object.entries(outputs)) emit(outDir, name, content);
emit(outDir, "version.ts", versionTS);
emit(testOutDir, "querycases.json", queryCasesJSON);
for (const w of warnings) console.warn(`sync-assets: warning: ${w}`);
for (const w of testWarnings) console.warn(`sync-assets: warning: ${w}`);
if (check && stale) {
  console.error("sync-assets: src/generated or test/generated is out of date; run npm run sync");
  process.exit(1);
}
if (!check) {
  console.log(
    `sync-assets: ${stale ? "updated" : "up to date"} src/generated (sdk, ${hubFiles.length} hub files, ${refs.length} references, ${mcpCatalog.tools.length} connector tools, version ${buildVersion()}) and test/generated`,
  );
}
