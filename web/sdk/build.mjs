#!/usr/bin/env node
// Generates the browser SDK builds from web/sdk/src/core.js (no dependencies).
//
//   node web/sdk/build.mjs           write backyard.js and backyard.mjs
//   node web/sdk/build.mjs --check   exit 1 when the committed files are stale
//
// core.js defines createBackyard(globalObject) and has no import/export
// statements. The outputs are complete, standalone files: the Go server and
// the Cloudflare Worker serve them byte-for-byte, prefixed with the
// per-request preamble `globalThis.__BACKYARD__ = {...};` (SPEC §2.1).

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));

/** Shared-instance key: both builds reuse one SDK instance per page. */
const INSTANCE_KEY = 'Symbol.for("backyard.sdk")';

/** Names exported by backyard.mjs besides the default export. */
export const NAMED_EXPORTS = ["db", "files", "ai", "warehouse", "socket", "id", "site", "me", "configure", "ready", "BackyardError"];

/** Reads the version constant from core.js. */
function versionOf(core) {
  const m = /const VERSION = "([^"]+)";/.exec(core);
  if (!m) throw new Error("core.js: VERSION constant not found");
  return m[1];
}

/** Validates core.js: a single factory and no module syntax. */
export function validateCore(core) {
  const lines = core.split("\n");
  lines.forEach((line, i) => {
    if (/^\s*(import|export)\b/.test(line) && !/^\s*(\/\/|\*)/.test(line)) {
      throw new Error(`core.js:${i + 1}: import/export statements are not allowed (the file is wrapped by build.mjs)`);
    }
  });
  if (!/^function createBackyard\(g\) \{$/m.test(core)) throw new Error("core.js must define `function createBackyard(g) {` at the top level");
  if (core.includes("\r")) throw new Error("core.js must use LF line endings");
}

/** Builds both outputs from the core source; returns { classic, module }. */
export function build(core) {
  validateCore(core);
  const version = versionOf(core);
  const body = core.endsWith("\n") ? core : core + "\n";
  const banner = (kind) =>
    `/*! Backyard client SDK v${version} (${kind}) | Apache-2.0 | https://github.com/thasami/backyard\n` +
    ` * GENERATED by web/sdk/build.mjs from web/sdk/src/core.js. Do not edit; run \`node web/sdk/build.mjs\`.\n` +
    ` * Typings: /__backyard/backyard.d.ts */\n`;

  const classic =
    banner("classic script: window.backyard") +
    `(function () {\n` +
    `"use strict";\n` +
    body +
    `var g = typeof globalThis !== "undefined" ? globalThis : typeof self !== "undefined" ? self : window;\n` +
    `var key = ${INSTANCE_KEY};\n` +
    `var sdk = g[key] || (g[key] = createBackyard(g));\n` +
    `g.backyard = sdk;\n` +
    `})();\n`;

  const module =
    banner("ES module") +
    body +
    `const backyard = globalThis[${INSTANCE_KEY}] || (globalThis[${INSTANCE_KEY}] = createBackyard(globalThis));\n` +
    `export default backyard;\n` +
    `export const { ${NAMED_EXPORTS.join(", ")} } = backyard;\n`;

  return { classic, module };
}

/** Paths of the source and the generated files. */
export const paths = {
  core: join(here, "src", "core.js"),
  classic: join(here, "backyard.js"),
  module: join(here, "backyard.mjs"),
};

function main(argv) {
  const check = argv.includes("--check");
  const out = build(readFileSync(paths.core, "utf8"));
  const targets = [
    [paths.classic, out.classic],
    [paths.module, out.module],
  ];
  let stale = 0;
  for (const [file, content] of targets) {
    let current = null;
    try {
      current = readFileSync(file, "utf8");
    } catch {
      current = null;
    }
    if (current === content) continue;
    if (check) {
      console.error(`stale: ${file} (run: node web/sdk/build.mjs)`);
      stale++;
    } else {
      writeFileSync(file, content);
      console.log(`wrote ${file}`);
    }
  }
  if (stale) process.exit(1);
  if (check) console.log("SDK builds are up to date");
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main(process.argv.slice(2));
}
